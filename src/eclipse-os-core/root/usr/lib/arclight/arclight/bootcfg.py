"""arclight-bootcfg: write the Arclight GRUB menu from /etc/arclight/boot.json.

One generator for every layout, used by the installer and by the installed system (after a
rename with arclight-identity, or a kernel parameter change):
  mode "deploy": side-by-side install living in a directory of an existing filesystem;
                 the root is that directory, mounted with rootflags=X-mount.subdir=...
  mode "btrfs":  whole-disk install, root in subvolume @ (kernel in /@/boot, so snapshots stay consistent)
The menu also chainloads any boot loader that was on the ESP before (e.g. the old Arch's GRUB).
"""
import json
import os
import sys
from pathlib import Path

from . import identity

CONF = Path("/etc/arclight/boot.json")


def render(c, name):
    theme = c.get("theme_dir_rel", "themes/arclight")
    lines = [
        "# Generated by arclight-bootcfg from /etc/arclight/boot.json. Do not edit: run arclight-bootcfg.",
        "insmod part_gpt", "insmod part_msdos", "insmod fat", "insmod ext2", "insmod btrfs",
        "insmod all_video", "insmod gfxterm", "insmod gfxmenu", "insmod png", "insmod search_fs_uuid",
        "set gfxmode=auto",
        f"if loadfont $prefix/{theme}/inter-16.pf2; then",
        f"    loadfont $prefix/{theme}/inter-20.pf2",
        f"    loadfont $prefix/{theme}/inter-24.pf2",
        "    terminal_output gfxterm",
        f"    set theme=$prefix/{theme}/theme.txt",
        "    export theme",
        "fi",
        "set default=0",
        f"set timeout={c.get('timeout', 4)}",
        "set timeout_style=menu",
        f"search --no-floppy --fs-uuid --set=arcroot {c['root_uuid']}",
        "",
    ]
    if c["mode"] == "deploy":
        sub = c["deploy"].strip("/")
        kdir = "/" + sub + "/boot"
        btr = "subvolid=5," if c.get("fstype") == "btrfs" else ""
        rootargs = f"root=UUID={c['root_uuid']} rootflags={btr}X-mount.subdir={sub} rw"
    elif c["mode"] == "btrfs":
        sv = c.get("subvol", "@")
        kdir = f"/{sv}/boot"
        rootargs = f"root=UUID={c['root_uuid']} rootflags=subvol={sv} rw"
    else:
        kdir = "/boot"
        rootargs = f"root=UUID={c['root_uuid']} rw"
    params = c.get("kernel_params", "quiet loglevel=3 splash rd.udev.log_level=3 vt.global_cursor_default=0")
    for title, img, extra in ((name, "initramfs-linux.img", ""),
                              (f"{name} (fallback initramfs)", "initramfs-linux-fallback.img", ""),
                              (f"{name} (console, no desktop)", "initramfs-linux.img", " systemd.unit=multi-user.target")):
        lines += [
            f'menuentry "{title}" --class arclight --class gnu-linux --class os {{',
            "    set root=$arcroot",
            "    set gfxpayload=keep",
            f"    linux {kdir}/vmlinuz-linux {rootargs} {params}{extra}",
            f"    initrd {kdir}/{img}",
            "}",
        ]
    for ch in c.get("chain", []):
        lines += [
            f'menuentry "{ch["label"]}" --class os {{',
            f"    search --no-floppy --fs-uuid --set=chainesp {ch['esp_uuid']}",
            f"    chainloader ($chainesp){ch['path']}",
            "}",
        ]
    if c.get("firmware") == "uefi":
        lines += ['menuentry "UEFI firmware settings" --class settings { fwsetup }']
    lines += ['menuentry "Power off" --class shutdown { halt }', 'menuentry "Restart" --class reboot { reboot }', ""]
    return "\n".join(lines)


def write(c, root="/"):
    name = identity.load(root)["name"]
    out = Path(root) / c["grub_cfg"].lstrip("/")
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".cfg.new")
    tmp.write_text(render(c, name))
    os.replace(tmp, out)
    return str(out)


def main(argv=None):
    root = os.environ.get("ARCLIGHT_ROOT", "/")
    conf = Path(root) / str(CONF).lstrip("/")
    if not conf.exists():
        print("arclight-bootcfg: no /etc/arclight/boot.json (this system's boot loader is not managed by Arclight)",
              file=sys.stderr)
        return 1
    c = json.loads(conf.read_text())
    print(write(c, root))
    return 0
